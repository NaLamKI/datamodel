"""SHACL shapes for the RDF projection of the model.

Two files, because they answer two different questions:

* `shapes.ttl` — is this record well-formed? It needs nothing but the record:
  types, cardinalities, enumerations, exclusive references (V03), positive
  quantities (V02), provenance (V04), period order (V01, V08), the
  conditional requirements of clause 8. Every shape is closed, so an
  attribute the model does not have is an error, as in the JSON Schema.
* `shapes-dataset.ttl` — does a dataset hold together? It needs the records
  referred to and the concept schemes: the class behind every reference, the
  scheme behind every classification, one default region per field (V05), a
  stand on the same region (V08), a plan entry of the same crop (V07), a
  product of the right category behind a plant protection application (V09).

The Turtle is written as text, not serialised by rdflib: the shapes are full of
blank nodes, and rdflib cannot serialise those reproducibly (the ontology hit
the same wall with its schema). Text written in a fixed order is identical on
every machine, which is what the guard on docs/ requires.
"""
from __future__ import annotations

from model import Attribute, Constraint, Entity, Model, Ontology

PREFIXES = {
    "agfoda": None,  # filled from the model
    "dct": "http://purl.org/dc/terms/",
    "geo": "http://www.opengis.net/ont/geosparql#",
    "owl": "http://www.w3.org/2002/07/owl#",
    "rdf": "http://www.w3.org/1999/02/22-rdf-syntax-ns#",
    "rdfs": "http://www.w3.org/2000/01/rdf-schema#",
    "sh": "http://www.w3.org/ns/shacl#",
    "shape": None,
    "skos": "http://www.w3.org/2004/02/skos/core#",
    "xsd": "http://www.w3.org/2001/XMLSchema#",
}

UUID = "[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}"


def lit(s: str) -> str:
    """A Turtle string literal."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def header(model: Model, which: str, title: str, description: str) -> str:
    prefixes = dict(PREFIXES, agfoda=model.ns, shape=f"{model.base_url}shapes#")
    out = [f"# {title}",
           "#",
           "# Generated by tool/build.py from model/ — do not edit.",
           ""]
    out += [f"@prefix {p}: <{iri}> ." for p, iri in sorted(prefixes.items())]
    out += ["",
            f"<{model.base_url}{which}> a owl:Ontology ;",
            f"    dct:title {lit(title)}@en ;",
            f"    dct:description {lit(description)}@en ;",
            f"    owl:versionInfo {lit(model.version)} ;",
            f"    dct:license <{model.meta['license']['url']}> .",
            ""]
    return "\n".join(out)


def _message(rule: str, text: str, entity: str) -> str:
    prefix = f"{rule}: " if rule else ""
    return lit(f"{prefix}{text} ({entity}).") + "@en"


def present(term: str) -> str:
    return f"[ sh:path agfoda:{term} ; sh:minCount 1 ]"


def group(entity: Entity, member) -> str:
    """One alternative of an exclusive reference: an attribute or a pair."""
    if isinstance(member, list):
        inner = " , ".join(present(entity.attributes[m].term) for m in member)
        return f"[ sh:property {inner} ]"
    return present(entity.attributes[member].term)


# --- record shapes --------------------------------------------------------

def _value_constraints(model: Model, ontology: Ontology, attr: Attribute) -> list[str]:
    t = attr.type
    if attr.references:
        return ["sh:nodeKind sh:IRI", f"sh:pattern {lit('^' + model.iri + UUID + '$')}"]
    if t == "UUID":
        return ["sh:datatype xsd:string", f"sh:pattern {lit('^' + UUID + '$')}"]
    if t == "Enum":
        values = " ".join(f"agfoda:{attr.enum}_{v}" for v in model.enum_values(attr.enum))
        return [f"sh:in ( {values} )"]
    if attr.concept:
        return ["sh:nodeKind sh:IRI"]
    if t == "JSON":
        if attr.geometry:
            return ["sh:or ( [ sh:datatype rdf:JSON ] [ sh:datatype geo:geoJSONLiteral ] )"]
        return ["sh:datatype rdf:JSON"]
    if t == "Decimal":
        return ["sh:or ( [ sh:datatype xsd:decimal ] [ sh:datatype xsd:double ] "
                "[ sh:datatype xsd:integer ] )"]
    return [f"sh:datatype xsd:{ {'String': 'string', 'Integer': 'integer', 'Boolean': 'boolean', 'Date': 'date', 'DateTime': 'dateTime'}[t] }"]


def property_shape(model: Model, ontology: Ontology, entity: Entity,
                   attr: Attribute) -> str:
    lines = [f"shape:{entity.name}-{attr.name} a sh:PropertyShape ;",
             f"    sh:path agfoda:{attr.term} ;",
             f"    sh:name {lit(attr.name)} ;"]
    lines += [f"    {c} ;" for c in _value_constraints(model, ontology, attr)]
    if attr.positive:
        lines.append("    sh:minExclusive 0 ;")
    if attr.required:
        lines.append("    sh:minCount 1 ;")
    if not attr.multivalued:
        lines.append("    sh:maxCount 1 ;")
    lines[-1] = lines[-1][:-2] + " ."
    return "\n".join(lines)


def constraint_shape(entity: Entity, c: Constraint, index: int) -> str | None:
    """A constraint as a node shape of its own, with its own message."""
    attrs = entity.attributes
    name = f"shape:{entity.name}-{c.rule or 'c'}-{index}"
    head = [f"{name} a sh:NodeShape ;",
            f"    sh:targetClass agfoda:{entity.name} ;",
            f"    sh:message {_message(c.rule or '', c.describe(), entity.name)} ;"]
    if c.level == "should":
        head.append("    sh:severity sh:Warning ;")
    if c.kind == "exactlyOne":
        body = "    sh:xone ( " + " ".join(group(entity, m) for m in c.members) + " ) ."
    elif c.kind == "atLeastOne":
        body = "    sh:or ( " + " ".join(group(entity, m) for m in c.members) + " ) ."
    elif c.kind == "atMostOne":
        names = c.members
        pairs = [(a, b) for n, a in enumerate(names) for b in names[n + 1:]]
        body = "    sh:not " + " ,\n        ".join(
            f"[ sh:property {present(attrs[a].term)} , {present(attrs[b].term)} ]"
            for a, b in pairs) + " ."
    elif c.kind == "requiredTogether":
        both = "[ sh:property " + " , ".join(present(attrs[m].term) for m in c.members) + " ]"
        none = "[ sh:not [ sh:or ( " + " ".join(present(attrs[m].term) for m in c.members) + " ) ] ]"
        body = f"    sh:or ( {both} {none} ) ."
    elif c.kind == "requiredWhen":
        (key, values), = c.when.items()
        cond_attr = attrs[key]
        individuals = " ".join(f"agfoda:{cond_attr.enum}_{v}" for v in values)
        condition = (f"[ sh:path agfoda:{cond_attr.term} ; sh:minCount 1 ; "
                     f"sh:in ( {individuals} ) ]")
        body = (f"    sh:or ( [ sh:not {condition} ] "
                f"{present(attrs[c.attribute].term)} ) .")
    elif c.kind == "order":
        # The comparison sits in a property shape; its results carry the
        # message of that shape, not of the node shape around it.
        first, second = (attrs[m].term for m in c.members)
        message = _message(c.rule or '', c.describe(), entity.name)
        body = (f"    sh:property [ sh:path agfoda:{first} ; "
                f"sh:lessThanOrEquals agfoda:{second} ;\n"
                f"        sh:message {message} ] .")
    else:
        return None
    return "\n".join(head + [body])


def record_shapes(model: Model, ontology: Ontology) -> str:
    out = [header(model, "shapes", "AgriFoodData model – record shapes",
                  "SHACL shapes for a single record of the AgriFoodData model "
                  "in its RDF projection (context.jsonld). Closed: a property "
                  "the model does not define is a violation.")]
    for e in model.ordered():
        attrs = list(e.attributes.values())
        out.append(f"# --- {e.name} ({e.package}, Annex {e.annex}) " + "-" * max(
            0, 50 - len(e.name)))
        out.append("\n".join([
            f"shape:{e.name} a sh:NodeShape ;",
            f"    rdfs:label {lit(e.name)} ;",
            f"    sh:targetClass agfoda:{e.name} ;",
            "    sh:closed true ;",
            "    sh:ignoredProperties ( rdf:type ) ;",
            "    sh:property " + " ,\n        ".join(
                f"shape:{e.name}-{a.name}" for a in attrs) + " .",
        ]))
        for a in attrs:
            out.append(property_shape(model, ontology, e, a))
        constraints = list(e.all_constraints)
        # V01 and V08: the order of the two ends of a period.
        for first, second in model.v01_pairs(e):
            constraints.append(Constraint(kind="order", members=[first, second],
                                          rule="V01"))
        for n, c in enumerate(constraints, 1):
            shape = constraint_shape(e, c, n)
            if shape:
                out.append(shape)
        out.append("")
    return "\n\n".join(out).rstrip() + "\n"


# --- dataset shapes -------------------------------------------------------

def dataset_shapes(model: Model, ontology: Ontology) -> str:
    out = [header(model, "shapes-dataset", "AgriFoodData model – dataset shapes",
                  "SHACL shapes for a dataset of the AgriFoodData model: they "
                  "need the records referred to and the concept schemes of the "
                  "ontology in the data graph.")]

    schemes = sorted({s for v in ontology.bindings.values() for s in v}
                     | set(ontology.notation_from.values()))
    out.append("# --- concept schemes " + "-" * 50)
    for s in schemes:
        sid = s.rsplit("/", 1)[-1]
        out.append(f"shape:in-{sid} a sh:NodeShape ;\n"
                   f"    rdfs:label {lit('concept of ' + sid)} ;\n"
                   f"    sh:property [ sh:path skos:inScheme ; sh:hasValue <{s}> ] .")

    for e in model.ordered():
        lines: list[str] = []
        refs = [a for a in e.attributes.values() if a.references]
        if refs:
            lines.append("\n".join([
                f"shape:{e.name}-references a sh:NodeShape ;",
                f"    sh:targetClass agfoda:{e.name} ;",
                "    sh:property " + " ,\n        ".join(
                    f"[ sh:path agfoda:{a.term} ; sh:class agfoda:{a.references} ;\n"
                    f"          sh:message {_message('', f'A reference points at a record of the entity it names: {a.name} at {a.references}', e.name)} ]"
                    for a in refs) + " ."]))
        bound = [(a, ontology.bindings[(e.name, a.term)]) for a in e.attributes.values()
                 if (e.name, a.term) in ontology.bindings]
        if bound:
            parts = []
            for a, ss in bound:
                shapes_ = [f"shape:in-{s.rsplit('/', 1)[-1]}" for s in ss]
                # Several schemes are alternatives: the ontology binds them
                # with one restriction over their union.
                check = (f"sh:node {shapes_[0]}" if len(shapes_) == 1
                         else "sh:or ( " + " ".join(shapes_) + " )")
                ids = " or ".join(s.rsplit("/", 1)[-1] for s in ss)
                message = _message('', f'{a.name} is a concept of the scheme {ids}', e.name)
                parts.append(f"[ sh:path agfoda:{a.term} ; {check} ;\n"
                             f"          sh:message {message} ]")
            lines.append("\n".join([
                f"shape:{e.name}-schemes a sh:NodeShape ;",
                f"    sh:targetClass agfoda:{e.name} ;",
                "    sh:property " + " ,\n        ".join(parts) + " ."]))
        for a in e.attributes.values():
            scheme = ontology.notation_from.get(a.term)
            if a.term in ontology.notation_from and a.name in e.own:
                query = (
                    "SELECT $this ?value WHERE { "
                    f"$this <{model.ns}{a.term}> ?value . "
                    "FILTER NOT EXISTS { "
                    f"?concept <{PREFIXES['skos']}inScheme> <{scheme}> ; "
                    f"<{PREFIXES['skos']}notation> ?notation . "
                    "FILTER (STR(?notation) = STR(?value)) } }")
                lines.append("\n".join([
                    f"shape:{e.name}-{a.name}-notation a sh:NodeShape ;",
                    f"    sh:targetClass agfoda:{e.name} ;",
                    "    sh:sparql [",
                    f"        sh:message {lit(a.name + ' {?value} is not a notation of ' + scheme)}@en ;",
                    f"        sh:select {lit(query)} ] ."]))
        if lines:
            out.append(f"# --- {e.name} " + "-" * max(0, 60 - len(e.name)))
            out.extend(lines)

    out.append("# --- rules across records " + "-" * 44)
    out.extend(_rules(model, ontology))
    return "\n\n".join(out).rstrip() + "\n"


def _rules(model: Model, ontology: Ontology) -> list[str]:
    default = ontology.concept(**model.rules["V05"]["concepts"]["default"])
    application = ontology.concept(**model.rules["V09"]["concepts"]["application"])
    return [
        # V05: exactly one default region per field.
        "\n".join([
            "shape:Field-V05 a sh:NodeShape ;",
            "    sh:targetClass agfoda:Field ;",
            "    sh:property [",
            "        sh:path [ sh:inversePath agfoda:fieldId ] ;",
            "        sh:qualifiedValueShape [ sh:class agfoda:Region ;",
            f"            sh:property [ sh:path agfoda:typeUri ; sh:hasValue <{default}> ] ] ;",
            "        sh:qualifiedMinCount 1 ;",
            "        sh:qualifiedMaxCount 1 ;",
            f"        sh:message {_message('V05', 'Every Field has exactly one default Region', 'Field')} ] ."]),
        # V07: a cultivation period from a plan entry grows the planned crop.
        "\n".join([
            "shape:CultivationPeriod-V07 a sh:NodeShape ;",
            "    sh:targetClass agfoda:CultivationPeriod ;",
            "    sh:severity sh:Warning ;",
            f"    sh:message {_message('V07', 'Where planEntryId is set, typeUri should correspond to CroppingPlanEntry.cropUri', 'CultivationPeriod')} ;",
            "    sh:or ( [ sh:path agfoda:planEntryId ; sh:maxCount 0 ]",
            "            [ sh:path ( agfoda:planEntryId agfoda:cropUri ) ; sh:equals agfoda:typeUri ] ) ."]),
        # V08: the stand of a cultivation period lies on the same region.
        "\n".join([
            "shape:CultivationPeriod-V08 a sh:NodeShape ;",
            "    sh:targetClass agfoda:CultivationPeriod ;",
            f"    sh:message {_message('V08', 'standId references a Stand of the same Region', 'CultivationPeriod')} ;",
            "    sh:or ( [ sh:path agfoda:standId ; sh:maxCount 0 ]",
            "            [ sh:path ( agfoda:standId agfoda:regionId ) ; sh:equals agfoda:regionId ] ) ."]),
        # V09: a plant protection application has its product.
        "\n".join([
            "shape:Activity-V09 a sh:NodeShape ;",
            "    sh:targetClass agfoda:Activity ;",
            f"    sh:message {_message('V09', 'An application of a plant protection product has an InputOutput referencing a Product of category PLANT_PROTECTION', 'Activity')} ;",
            f"    sh:or ( [ sh:not [ sh:path agfoda:typeUri ; sh:hasValue <{application}> ] ]",
            "            [ sh:path [ sh:inversePath agfoda:activityId ] ;",
            "              sh:qualifiedValueShape [ sh:class agfoda:InputOutput ;",
            "                  sh:property [ sh:path ( agfoda:productId agfoda:category ) ;",
            "                                sh:hasValue agfoda:ProductCategory_PLANT_PROTECTION ] ] ;",
            "              sh:qualifiedMinCount 1 ] ) ."]),
        "\n".join([
            "shape:Activity-V09-bbch a sh:NodeShape ;",
            "    sh:targetClass agfoda:Activity ;",
            "    sh:severity sh:Warning ;",
            f"    sh:message {_message('V09', 'An application of a plant protection product should carry bbchStage', 'Activity')} ;",
            f"    sh:or ( [ sh:not [ sh:path agfoda:typeUri ; sh:hasValue <{application}> ] ]",
            "            [ sh:path agfoda:bbchStage ; sh:minCount 1 ] ) ."]),
    ]
